"""How far each portrait must slide sideways so the player's head and chest sit in the middle of a card (an arm held out must not pull the body off-centre).
Writes src/game/portraitShift.ts, percentages of the image's own width.

  python -I tools/portrait_centres.py
"""
import glob, os
import numpy as np
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = {}
for path in sorted(glob.glob(os.path.join(root, 'public', 'portraits', '*_s*.webp'))):
    name = os.path.basename(path).rsplit('_', 1)[0]
    a = np.asarray(Image.open(path).convert('RGBA'))[..., 3] > 40
    rows = np.where(a.any(axis=1))[0]
    if not len(rows):
        continue
    top = rows[0]
    h = a.shape[0] - top
    w = a.shape[1]
    # the head is the narrow top of the figure; the chest is the middle of each row's run, which an outstretched arm barely moves when medians are used
    head = np.where(a[top:top + int(h * 0.26)])[1]
    mids = []
    for y in range(top + int(h * 0.3), top + int(h * 0.8), 3):
        xs = np.where(a[y])[0]
        if len(xs):
            mids.append(np.median(xs))
    centre = 0.65 * np.median(head) + 0.35 * (np.median(mids) if mids else np.median(head))
    out[name] = round((w / 2 - centre) / w * 100, 1)
lines = ['// Generated by tools/portrait_centres.py: sideways slide (% of the image width) that centres each player on a card', 'export const PORTRAIT_SHIFT: Record<string, number> = {']
lines += [f"  {k}: {v}," for k, v in out.items() if abs(v) >= 0.5]
lines += ['};', '']
open(os.path.join(root, 'src', 'game', 'portraitShift.ts'), 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print({k: v for k, v in out.items() if abs(v) >= 3})
